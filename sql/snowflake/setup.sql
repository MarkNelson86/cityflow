-- Create isolated CityFlow objects in Snowsight as ACCOUNTADMIN.
-- Keep the user placeholder in the committed file; substitute it only in Snowsight.
-- Do not use CREATE OR REPLACE. Reruns should fail rather than overwrite objects.
USE ROLE ACCOUNTADMIN;

CREATE RESOURCE MONITOR CITYFLOW_MONITOR
    WITH CREDIT_QUOTA = 5
    FREQUENCY = MONTHLY
    START_TIMESTAMP = IMMEDIATELY
    TRIGGERS
        ON 80 PERCENT DO SUSPEND
        ON 100 PERCENT DO SUSPEND_IMMEDIATE;

CREATE WAREHOUSE CITYFLOW_WH
    WITH WAREHOUSE_SIZE = 'XSMALL'
    WAREHOUSE_TYPE = 'STANDARD'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    ENABLE_QUERY_ACCELERATION = FALSE
    STATEMENT_TIMEOUT_IN_SECONDS = 600
    RESOURCE_MONITOR = CITYFLOW_MONITOR;

CREATE ROLE CITYFLOW_ROLE;

GRANT ROLE CITYFLOW_ROLE TO USER YOUR_SNOWFLAKE_USER;
GRANT USAGE, OPERATE ON WAREHOUSE CITYFLOW_WH TO ROLE CITYFLOW_ROLE;

CREATE DATABASE CITYFLOW_FIXTURE;
CREATE DATABASE CITYFLOW_REAL;

GRANT OWNERSHIP ON DATABASE CITYFLOW_FIXTURE
    TO ROLE CITYFLOW_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON DATABASE CITYFLOW_REAL
    TO ROLE CITYFLOW_ROLE COPY CURRENT GRANTS;

USE ROLE CITYFLOW_ROLE;

CREATE SCHEMA CITYFLOW_FIXTURE.RAW;
CREATE SCHEMA CITYFLOW_FIXTURE.META;
CREATE SCHEMA CITYFLOW_FIXTURE.ANALYTICS;
CREATE SCHEMA CITYFLOW_REAL.RAW;
CREATE SCHEMA CITYFLOW_REAL.META;
CREATE SCHEMA CITYFLOW_REAL.ANALYTICS;

SHOW WAREHOUSES LIKE 'CITYFLOW_WH';
