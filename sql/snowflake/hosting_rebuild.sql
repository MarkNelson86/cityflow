USE ROLE ACCOUNTADMIN;
CREATE RESOURCE MONITOR CITYFLOW_MONITOR WITH CREDIT_QUOTA=5
    FREQUENCY=MONTHLY START_TIMESTAMP=IMMEDIATELY
    TRIGGERS ON 80 PERCENT DO SUSPEND ON 100 PERCENT DO SUSPEND_IMMEDIATE;
CREATE WAREHOUSE CITYFLOW_WH WAREHOUSE_SIZE='XSMALL' WAREHOUSE_TYPE='STANDARD'
    AUTO_SUSPEND=60 AUTO_RESUME=TRUE INITIALLY_SUSPENDED=TRUE
    STATEMENT_TIMEOUT_IN_SECONDS=600 RESOURCE_MONITOR=CITYFLOW_MONITOR
    ENABLE_QUERY_ACCELERATION=FALSE;
CREATE ROLE CITYFLOW_ROLE;
GRANT ROLE CITYFLOW_ROLE TO USER YOUR_SQL_USERNAME;
GRANT USAGE, OPERATE ON WAREHOUSE CITYFLOW_WH TO ROLE CITYFLOW_ROLE;
CREATE DATABASE CITYFLOW_REAL;
GRANT OWNERSHIP ON DATABASE CITYFLOW_REAL TO ROLE CITYFLOW_ROLE COPY CURRENT GRANTS;
USE ROLE CITYFLOW_ROLE;
CREATE SCHEMA CITYFLOW_REAL.RAW;
CREATE SCHEMA CITYFLOW_REAL.META;
CREATE SCHEMA CITYFLOW_REAL.ANALYTICS;
-- Verify resource settings separately as ACCOUNTADMIN.
USE ROLE ACCOUNTADMIN;
SHOW WAREHOUSES LIKE 'CITYFLOW_WH';
SHOW RESOURCE MONITORS LIKE 'CITYFLOW_MONITOR';
