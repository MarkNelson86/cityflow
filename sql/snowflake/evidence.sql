USE ROLE CITYFLOW_ROLE;
USE WAREHOUSE CITYFLOW_WH;
USE DATABASE CITYFLOW_REAL;

ALTER SESSION SET QUERY_TAG = 'cityflow_snowflake_evidence';

SELECT COUNT(*) AS OBSERVED_RECORDS
FROM ANALYTICS.FACT_TRIPS
WHERE IS_OBSERVED_TRIP;

SELECT
    DATE_TRUNC('MONTH', PICKUP_DATE)::DATE AS MONTH_START,
    COUNT(*) AS TRIP_COUNT,
    COUNT(CASE WHEN IS_DURATION_ELIGIBLE THEN 1 END) AS DURATION_RECORDS,
    COUNT(CASE WHEN IS_FARE_ELIGIBLE THEN 1 END) AS FARE_RECORDS,
    MEDIAN(
        CASE WHEN IS_DURATION_ELIGIBLE THEN DURATION_MINUTES END
    ) AS MEDIAN_DURATION_MINUTES,
    PERCENTILE_CONT(0.9) WITHIN GROUP (
        ORDER BY CASE
            WHEN IS_DURATION_ELIGIBLE THEN DURATION_MINUTES
        END
    ) AS P90_DURATION_MINUTES,
    MEDIAN(
        CASE WHEN IS_FARE_ELIGIBLE THEN FARE_AMOUNT END
    ) AS MEDIAN_FARE_USD
FROM ANALYTICS.FACT_TRIPS
WHERE IS_OBSERVED_TRIP
GROUP BY 1
ORDER BY 1;

ALTER SESSION UNSET QUERY_TAG;

-- Query history visible to this role, filtered to CityFlow-tagged queries.
SELECT
    QUERY_ID,
    QUERY_TYPE,
    EXECUTION_STATUS,
    START_TIME,
    END_TIME,
    TOTAL_ELAPSED_TIME,
    BYTES_SCANNED,
    ROWS_PRODUCED,
    WAREHOUSE_NAME,
    QUERY_TAG
FROM TABLE(
    INFORMATION_SCHEMA.QUERY_HISTORY(
        END_TIME_RANGE_END => CURRENT_TIMESTAMP(),
        RESULT_LIMIT => 10000
    )
)
WHERE QUERY_TAG LIKE 'cityflow_snowflake%'
ORDER BY START_TIME;
