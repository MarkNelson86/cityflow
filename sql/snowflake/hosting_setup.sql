-- Only after the real build and full parity pass. Run one block at a time.
-- Block A: project owner materializes bounded serving tables.
USE ROLE CITYFLOW_ROLE;
USE WAREHOUSE CITYFLOW_WH;
ALTER SESSION SET QUERY_TAG='cityflow_hosting_prepare';
CREATE SCHEMA CITYFLOW_REAL.SERVING;
CREATE TABLE CITYFLOW_REAL.SERVING.APP_METADATA AS
SELECT 'real'::VARCHAR AS DATASET,
    (SELECT COUNT(*) FROM CITYFLOW_REAL.RAW.TRIPS) AS RAW_RECORDS,
    (SELECT COUNT(*) FROM CITYFLOW_REAL.ANALYTICS.FACT_TRIPS WHERE IS_OBSERVED_TRIP) AS OBSERVED_RECORDS,
    (SELECT MIN(MINIMUM_METRIC_RECORDS) FROM CITYFLOW_REAL.ANALYTICS.MART_ROUTE_MONTHLY) AS MINIMUM_METRIC_RECORDS,
    (SELECT COUNT(*) FROM CITYFLOW_REAL.ANALYTICS.MART_ROUTE_MONTHLY) AS FULL_ROUTE_MONTH_ROWS;
CREATE TABLE CITYFLOW_REAL.SERVING.APP_DAILY AS
SELECT DATE_DAY, TRIP_COUNT,
    CASE WHEN COUNT(TRIP_COUNT) OVER (ORDER BY DATE_DAY ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) = 7
         THEN AVG(TRIP_COUNT::FLOAT) OVER (ORDER BY DATE_DAY ROWS BETWEEN 6 PRECEDING AND CURRENT ROW)
    END AS TRAILING_7_DAY_MEAN
FROM CITYFLOW_REAL.ANALYTICS.MART_DAILY_ACTIVITY;
CREATE TABLE CITYFLOW_REAL.SERVING.APP_MONTHLY AS
WITH CALENDAR AS (
    SELECT MONTH_START, COUNT(*) AS SELECTED_CALENDAR_DAYS
    FROM CITYFLOW_REAL.ANALYTICS.DIM_DATES GROUP BY 1
), ACTIVITY AS (
    SELECT DATE_TRUNC('MONTH', PICKUP_DATE)::DATE AS MONTH_START,
        COUNT(*) AS TRIP_COUNT,
        COUNT(CASE WHEN IS_DURATION_ELIGIBLE THEN 1 END) AS DURATION_RECORDS,
        COUNT(CASE WHEN IS_FARE_ELIGIBLE THEN 1 END) AS FARE_RECORDS,
        MEDIAN(CASE WHEN IS_DURATION_ELIGIBLE THEN DURATION_MINUTES END) AS MEDIAN_DURATION_MINUTES,
        PERCENTILE_CONT(0.9) WITHIN GROUP (ORDER BY CASE WHEN IS_DURATION_ELIGIBLE THEN DURATION_MINUTES END) AS P90_DURATION_MINUTES,
        MEDIAN(CASE WHEN IS_FARE_ELIGIBLE THEN FARE_AMOUNT END) AS MEDIAN_FARE_USD
    FROM CITYFLOW_REAL.ANALYTICS.FACT_TRIPS WHERE IS_OBSERVED_TRIP GROUP BY 1
)
SELECT C.MONTH_START, C.SELECTED_CALENDAR_DAYS, COALESCE(A.TRIP_COUNT, 0) AS TRIP_COUNT,
    COALESCE(A.TRIP_COUNT, 0)::FLOAT / C.SELECTED_CALENDAR_DAYS AS TRIPS_PER_CALENDAR_DAY,
    COALESCE(A.DURATION_RECORDS, 0) AS DURATION_RECORDS,
    COALESCE(A.FARE_RECORDS, 0) AS FARE_RECORDS,
    A.MEDIAN_DURATION_MINUTES, A.P90_DURATION_MINUTES, A.MEDIAN_FARE_USD
FROM CALENDAR C LEFT JOIN ACTIVITY A USING (MONTH_START);
CREATE TABLE CITYFLOW_REAL.SERVING.APP_ROUTES AS
WITH TOTALS AS (
    SELECT ROUTE_KEY, IS_GEOGRAPHIC_ROUTE, SUM(TRIP_COUNT) AS QUARTER_TRIPS
    FROM CITYFLOW_REAL.ANALYTICS.MART_ROUTE_MONTHLY GROUP BY 1, 2
), SELECTED AS (
    SELECT ROUTE_KEY FROM TOTALS
    QUALIFY ROW_NUMBER() OVER (PARTITION BY IS_GEOGRAPHIC_ROUTE ORDER BY QUARTER_TRIPS DESC, ROUTE_KEY)
        <= CASE WHEN IS_GEOGRAPHIC_ROUTE THEN 100 ELSE 5 END
)
SELECT M.ROUTE_KEY, M.MONTH_START, M.PICKUP_ZONE_NAME, M.DROPOFF_ZONE_NAME,
    M.PICKUP_BOROUGH, M.DROPOFF_BOROUGH, M.IS_GEOGRAPHIC_ROUTE, M.TRIP_COUNT,
    M.CALENDAR_DAYS, M.TRIPS_PER_CALENDAR_DAY, M.DURATION_RECORDS, M.FARE_RECORDS,
    M.MINIMUM_METRIC_RECORDS, M.DURATION_SAMPLE_SUFFICIENT, M.FARE_SAMPLE_SUFFICIENT,
    CASE WHEN M.DURATION_SAMPLE_SUFFICIENT THEN M.MEDIAN_DURATION_MINUTES END AS MEDIAN_DURATION_MINUTES,
    CASE WHEN M.DURATION_SAMPLE_SUFFICIENT THEN M.P90_DURATION_MINUTES END AS P90_DURATION_MINUTES,
    CASE WHEN M.FARE_SAMPLE_SUFFICIENT THEN M.MEDIAN_FARE_USD END AS MEDIAN_FARE_USD,
    M.VOLUME_RANK, M.PREVIOUS_MONTH_START, M.PREVIOUS_TRIP_COUNT, M.TRIPS_PER_DAY_CHANGE_PCT,
    M.MEDIAN_DURATION_CHANGE_MINUTES, M.MEDIAN_FARE_CHANGE_USD
FROM CITYFLOW_REAL.ANALYTICS.MART_ROUTE_MONTH_COMPARISON M JOIN SELECTED S USING (ROUTE_KEY);
-- Block B: dedicated read-only service identity and separately limited compute.
USE ROLE ACCOUNTADMIN;
CREATE RESOURCE MONITOR CITYFLOW_APP_MONITOR WITH CREDIT_QUOTA=1
    FREQUENCY=DAILY START_TIMESTAMP=IMMEDIATELY
    TRIGGERS ON 80 PERCENT DO SUSPEND ON 100 PERCENT DO SUSPEND_IMMEDIATE;
CREATE WAREHOUSE CITYFLOW_APP_WH WAREHOUSE_SIZE='XSMALL' WAREHOUSE_TYPE='STANDARD'
    AUTO_SUSPEND=60 AUTO_RESUME=TRUE INITIALLY_SUSPENDED=TRUE
    STATEMENT_TIMEOUT_IN_SECONDS=60 RESOURCE_MONITOR=CITYFLOW_APP_MONITOR
    ENABLE_QUERY_ACCELERATION=FALSE;
CREATE ROLE CITYFLOW_APP_ROLE;
CREATE USER CITYFLOW_APP_USER TYPE=SERVICE
    DEFAULT_ROLE='CITYFLOW_APP_ROLE' DEFAULT_WAREHOUSE='CITYFLOW_APP_WH'
    RSA_PUBLIC_KEY='YOUR_PUBLIC_KEY_BODY';
GRANT ROLE CITYFLOW_APP_ROLE TO USER CITYFLOW_APP_USER;
GRANT USAGE ON WAREHOUSE CITYFLOW_APP_WH TO ROLE CITYFLOW_APP_ROLE;
-- Block C: database owner grants only four serving table reads.
USE ROLE CITYFLOW_ROLE;
GRANT USAGE ON DATABASE CITYFLOW_REAL TO ROLE CITYFLOW_APP_ROLE;
GRANT USAGE ON SCHEMA CITYFLOW_REAL.SERVING TO ROLE CITYFLOW_APP_ROLE;
GRANT SELECT ON TABLE CITYFLOW_REAL.SERVING.APP_METADATA TO ROLE CITYFLOW_APP_ROLE;
GRANT SELECT ON TABLE CITYFLOW_REAL.SERVING.APP_DAILY TO ROLE CITYFLOW_APP_ROLE;
GRANT SELECT ON TABLE CITYFLOW_REAL.SERVING.APP_MONTHLY TO ROLE CITYFLOW_APP_ROLE;
GRANT SELECT ON TABLE CITYFLOW_REAL.SERVING.APP_ROUTES TO ROLE CITYFLOW_APP_ROLE;
-- Block D: inspect role grants and compute controls.
USE ROLE ACCOUNTADMIN;
SHOW GRANTS TO ROLE CITYFLOW_APP_ROLE;
SHOW WAREHOUSES LIKE 'CITYFLOW_APP_WH';
SHOW RESOURCE MONITORS LIKE 'CITYFLOW_APP_MONITOR';
